#!/usr/bin/env node
/**
 * Writes netlify/functions/lib/places.mjs: every place in the service area, as
 * [name, state, market]. The lead function matches the town a visitor typed against it when
 * they leave out a ZIP code. Sources: every published town page, plus the per-market place
 * lists in src/data/cities/. Holden Beach is not served (Ty, 2026-09-13) and stays out.
 *
 * Run after adding towns:  node scripts/build-lead-places.mjs
 * tests/lead-routing.test.mjs fails when a published town is missing from the file.
 */
import { readFileSync, readdirSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = fileURLToPath(new URL('..', import.meta.url));
const NOT_SERVED = new Set(['holden-beach-nc']);
const MARKETS = ['denver-metro', 'grand-strand', 'northeast-florida'];
const places = new Map();
const add = (slug, name, state, market) => {
  if (!name || !state || !MARKETS.includes(market) || NOT_SERVED.has(slug)) return;
  const key = `${name.toLowerCase()}|${state}`;
  if (!places.has(key)) places.set(key, [name, state, market]);
};

const townsDir = join(root, 'src/content/towns');
for (const f of readdirSync(townsDir).filter((x) => x.endsWith('.json')).sort()) {
  const t = JSON.parse(readFileSync(join(townsDir, f), 'utf8'));
  if (t.status === 'published') add(f.replace(/\.json$/, ''), t.name, t.state, t.market);
}
for (const m of MARKETS) {
  for (const c of JSON.parse(readFileSync(join(root, `src/data/cities/${m}.json`), 'utf8'))) add(c.slug, c.name, c.state, c.market ?? m);
}

const rows = [...places.values()].sort((a, b) => b[0].length - a[0].length || a[0].localeCompare(b[0]));
const out = `// Generated by scripts/build-lead-places.mjs. Do not edit by hand; run the script.\n`
  + `// [name, state, market], longest name first so "Jacksonville Beach" matches before "Jacksonville".\n`
  + `export default ${JSON.stringify(rows, null, 0).replace(/\],\[/g, '],\n  [').replace(/^\[\[/, '[\n  [').replace(/\]\]$/, '],\n]')};\n`;
writeFileSync(join(root, 'netlify/functions/lib/places.mjs'), out);
console.log(`places: ${rows.length} written`);
